    public static function getText($index, $assign)
    {
        $data = self::getData();
        if (isset($data[$index]['block'])) {
            return $data[$index]['block'] . ' = ' . $assign;
        }
    }

    public static function getDropDown()
    {
        $result = [];
        foreach (self::getData() as $catIndex => $cat) {
            $elements = [];
            foreach ($cat['items'] as $index => $item) {
                $elements[$catIndex . '_' . $index] = $item;
            }
            $result[$cat['block']] = $elements;
        }
        return $result;
    }
